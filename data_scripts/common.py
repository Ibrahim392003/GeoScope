"""Shared paths, constants and helpers for the GeoScope data pipeline."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "data"          # git-ignored (raw + processed data)
FIG_DIR = ROOT / "figures"        # EDA charts used in the LaTeX report
REPORT_DIR = ROOT / "report"      # LaTeX report + small auto-generated logs

MANIFEST = DATA_DIR / "clean_manifest.csv"
SPLITS = DATA_DIR / "splits.csv"
LABEL_MAP = DATA_DIR / "label_map.json"

IMG_EXT = {".jpg", ".jpeg", ".png", ".tif", ".tiff"}
IMAGENET_MEAN = (0.485, 0.456, 0.406)
IMAGENET_STD = (0.229, 0.224, 0.225)
SEED = 42


def ensure_dirs():
    for d in (DATA_DIR, FIG_DIR, REPORT_DIR):
        d.mkdir(parents=True, exist_ok=True)


def find_image_root(data_dir=DATA_DIR):
    """Locate the folder that contains one sub-folder per class.

    torchvision stores EuroSAT as  data/eurosat/2750/<ClassName>/<ClassName>_N.jpg
    """
    data_dir = Path(data_dir)
    for cand in (data_dir / "eurosat" / "2750", data_dir / "2750",
                 data_dir / "EuroSAT", data_dir):
        if not cand.is_dir():
            continue
        for d in cand.iterdir():
            if d.is_dir() and any(f.suffix.lower() in IMG_EXT for f in d.iterdir()):
                return cand
    raise FileNotFoundError(
        f"No class folders with images found under {data_dir}. "
        "Run  python data_scripts/download_data.py  first.")


def list_images(root):
    """Return [(class_name, Path), ...] sorted for reproducibility."""
    out = []
    for d in sorted(p for p in Path(root).iterdir() if p.is_dir()):
        out.extend((d.name, f) for f in sorted(d.iterdir())
                   if f.suffix.lower() in IMG_EXT)
    return out


def update_stats(**kwargs):
    """Merge numbers into report/stats.json and regenerate report/stats.tex.

    The LaTeX report \\input's stats.tex, so every number in the report
    comes straight from the scripts (keys must be letters only).
    """
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    jp = REPORT_DIR / "stats.json"
    stats = json.loads(jp.read_text()) if jp.exists() else {}
    stats.update(kwargs)
    jp.write_text(json.dumps(stats, indent=2))
    lines = ["% AUTO-GENERATED by data_scripts/ - do not edit by hand"]
    for k, v in stats.items():
        assert k.isalpha(), f"stat key must be letters only: {k}"
        if isinstance(v, int):
            v = f"{v:,}".replace(",", "{,}")
        lines.append(f"\\newcommand{{\\stat{k}}}{{{v}}}")
    (REPORT_DIR / "stats.tex").write_text("\n".join(lines) + "\n")
